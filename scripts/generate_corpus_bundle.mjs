import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const agFolder = path.resolve(__dirname, '..', '..');
const notionOsDir = path.join(agFolder, 'notion_os');
const myNotesDir = path.join(agFolder, 'my_notes');
const outputFile = path.join(__dirname, '..', 'src', 'data', 'authenticCorpusArchive.ts');

function parseMarkdownDoc(filePath, category) {
  const filename = path.basename(filePath);
  const rawContent = fs.readFileSync(filePath, 'utf8');
  
  // Extract title from first # heading or filename
  let title = filename.replace(/\.md$/i, '');
  const titleMatch = rawContent.match(/^#\s+(.+)$/m);
  if (titleMatch) {
    title = titleMatch[1].trim();
  }

  // Extract Notion ID if present
  let notionId = undefined;
  const notionIdMatch = rawContent.match(/Notion ID:\s*`([^`]+)`/i);
  if (notionIdMatch) {
    notionId = notionIdMatch[1].trim();
  }

  const id = `${category === 'Notion OS Module' ? 'notion' : 'notes'}_${filename.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`;

  return {
    id,
    filename,
    title,
    notionId,
    category,
    content: rawContent,
    byteLength: Buffer.byteLength(rawContent, 'utf8')
  };
}

console.log('Scanning authentic archives in Ag Folder...');

const docs = [];

if (fs.existsSync(notionOsDir)) {
  const notionFiles = fs.readdirSync(notionOsDir).filter(f => f.endsWith('.md'));
  for (const file of notionFiles) {
    docs.push(parseMarkdownDoc(path.join(notionOsDir, file), 'Notion OS Module'));
  }
}

if (fs.existsSync(myNotesDir)) {
  const noteFiles = fs.readdirSync(myNotesDir).filter(f => f.endsWith('.md'));
  for (const file of noteFiles) {
    docs.push(parseMarkdownDoc(path.join(myNotesDir, file), 'My Notes Archive'));
  }
}

console.log(`Extracted ${docs.length} authentic markdown documents.`);
const totalBytes = docs.reduce((acc, d) => acc + d.byteLength, 0);
console.log(`Total corpus size: ${(totalBytes / 1024).toFixed(2)} KB`);

const tsContent = `/**
 * ? Om Knowledge OS ?" Authentic Raw Corpus Archive
 * Generated by scripts/generate_corpus_bundle.mjs
 * Total Files: ${docs.length} | Size: ${(totalBytes / 1024).toFixed(2)} KB
 */

export interface RawCorpusDoc {
  id: string;
  filename: string;
  title: string;
  notionId?: string;
  category: 'Notion OS Module' | 'My Notes Archive';
  content: string;
  byteLength: number;
}

export const AUTHENTIC_CORPUS_DOCS: RawCorpusDoc[] = ${JSON.stringify(docs, null, 2)};
`;

fs.writeFileSync(outputFile, tsContent, 'utf8');
console.log(`Wrote corpus archive to: ${outputFile}`);
